-- AMS_ORDERS
CREATE TABLE AMS_ORDERS (
  ORDER_ID              NUMBER(19) NOT NULL PRIMARY KEY,
  ORDER_NUMBER          VARCHAR(40),
  ORDER_TYPE_CD         VARCHAR(20),
  ORDER_STATUS_CD       VARCHAR(20),
  CUSTOMER_ID           NUMBER(19),
  ASSET_ID              NUMBER(19),
  SHIPPING_CARRIER_CD   VARCHAR(20),
  TRACKING_NUMBER       VARCHAR(60),
  SUBMITTED_DT          TIMESTAMP,
  SHIPPED_DT            TIMESTAMP,
  REQUESTED_INSTALL_DT  TIMESTAMP,
  CANCELLED_DT          TIMESTAMP,
  CANCELLATION_REASON   VARCHAR(400),
  CANCEL_PENALTY_FL     CHAR(1) DEFAULT 'N',
  COMMENTS              VARCHAR(2000),
  DEVICE_NICKNAME       VARCHAR(60),
  SHIP_ADDRESS_ID       NUMBER(19),
  ORDER_CONTACT_ID      NUMBER(19),
  SHIP_CONTACT_ID       NUMBER(19),
  INSTALL_CONTACT_ID    NUMBER(19),
  MAINT_WINDOW_ID       NUMBER(19),
  CONFIG_ID             NUMBER(19),
  SHIP_WINDOW_ID        NUMBER(19),
  CREATED_DT            TIMESTAMP,
  CREATED_BY            VARCHAR(64),
  MODIFIED_DT           TIMESTAMP,
  MODIFIED_BY           VARCHAR(64)
);
